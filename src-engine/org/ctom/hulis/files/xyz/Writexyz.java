	/**
	 * 
	 * @param out
	 */
	public void writeHeader(PrintWriter out) {
		out.println((this.geom.countAtoms()));
		if (this.messageHeader =="")
			out.println((Writexyz.MESSAGE_CREE_PAR ));
		else
			out.println(this.getMessageHeader());
		
	}

	/**
	 * 
	 * @param messageHeader
	 */
