package org.ctom.hulis.files.xyz;


import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

import org.ctom.hulis.files.Writer;
import org.ctom.hulis.huckel.Atom;
import org.ctom.hulis.huckel.exception.GeometryException;
import org.ctom.hulis.huckel.structures.Structure;
import org.ctom.hulis.huckel.structures.StructureDelocalized;
import org.ctom.hulis.util.geometry.Geometry;
import org.ctom.hulis.util.geometry.InitialOrientation;
import org.ctom.hulis.util.geometry.SuperSymbolComparator;

public class Writexyz {

	public final static String MESSAGE_CREE_PAR = "File generated by the HuliS code";
	Geometry geom;
	Structure s;
	Writer out;
	private boolean isWriteInitialOrientation;
	private boolean writeConnectivity;
	private String messageHeader;

	public Writexyz(StructureDelocalized s)  {
		this.s = s;
		this.isWriteInitialOrientation = false;
		this.writeConnectivity = false;
		this.messageHeader = "";
	
	}
	
	
	

	public Structure getStructure() {
		return this.s;
	}

	

	/**
	 * write the structure into the writer, in a xyz format
	 * @param out : the writer 
	 * @throws WritexyzException
	 */
	public void writeAll(Writer out) throws WritexyzException {
		try {
			//s.createGeometry();
			this.geom = s.getGeometry();
			// on clone la liste pour ne pas que la structure soit modifie par le remplacememtn de ME par CH3
			//this.geom.setListAtom((ArrayList<Atom>) ((ArrayList<Atom>) s.getAtoms()).clone() );
			//this.geom.replaceMEByCH3();
			this.out = out;
		} catch (GeometryException e) {
			throw new WritexyzException(e);
		}
		write(out);

	}
	
	/**
	 * 
	 * @param isWriteInitialOrientation
	 */
	public void setWriteInitialOrientation(boolean isWriteInitialOrientation) {
		this.isWriteInitialOrientation=isWriteInitialOrientation;
	}
	
	/**
	 * 
	 * @return
	 */
	public boolean isWriteInitialOrientation () {
		return this.isWriteInitialOrientation;
	}
	

	private void write(Writer out) {
		// PrintWriter out = null;
		writeHeader(out);

		int scale = this.geom.getscale();
		
		InitialOrientation initialOrientation = this.geom.getInitialOrientation();
		
		List <Atom >sortedGeom3D = new ArrayList <Atom>();
		sortedGeom3D.addAll(this.geom.getGeom3D());
		Collections.sort(sortedGeom3D,  new SuperSymbolComparator());
		
		for (Atom atom : sortedGeom3D) {
			String symbol = "";
			if (atom.getElement() == null)
				symbol = atom.getSigle();
			else
				symbol = atom.getElement().toString();
			double x;
			double y ;
			double z;
	
			if (this.isWriteInitialOrientation){
				x = atom.getLocationGeom().getX();
				y = atom.getLocationGeom().getY();
				z= atom.getLocationGeom().getZ();
			}
			else{
				x = atom.getLocation().getX();
				y = atom.getLocation().getY();
				z= atom.getLocation().getZ();
			}
			/*if (this.restoreInitialOrientation) {
				HuckelIO.PrintIf ("WriteXYZ.write(out) initial orientation restored = " + initialOrientation);

				x = x + initialOrientation.getOrigin().getX();
				x = y + initialOrientation.getOrigin().getY();
				z = z + initialOrientation.getOrigin().getZ();
				
				if (!Double.isNaN(angle)  && !initialOrientation.getAxis().isInfinite() &&  (initialOrientation.getAngle() % Math.PI != 0) ) 
		
				if (initialOrientation.getAngle() % Math.PI != 0) {
					VecteurCTOM v = new VecteurCTOM (x, y, z);
					v.rotate(initialOrientation.getAxis(), -initialOrientation.getAngle());
					x = v.getX();
					y = v.getY();
					z = v.getZ();
				}
			}*/
			
			// the locale is necessary to make sure to have . as number
			// separator
			out.printfUS("%s   %10.5f   %10.5f   %10.5f", symbol, x / scale, y / scale, z/ scale);
			if (this.writeConnectivity && atom.getConnect().size() != 0) {
				for (int i : atom.getConnect()) {
					out.printf("  %5d", i);
				}
			}
			out.println();
		}

		return;
	}

	public void writeHeader(Writer out) {
		out.println((this.geom.countAtoms()));
		if (this.messageHeader =="")
			out.println((Writexyz.MESSAGE_CREE_PAR ));
		else
			out.println(this.getMessageHeader());
		
	}

	public void setMessageHeader(String messageHeader){
		this.messageHeader = messageHeader;
	}
	
	public String getMessageHeader() {
		return this.messageHeader;
	}

	public boolean isWriteConnectivity() {
		return writeConnectivity;
	}




	public void setWriteConnectivity(boolean writeConnectivity) {
		this.writeConnectivity = writeConnectivity;
	}
}