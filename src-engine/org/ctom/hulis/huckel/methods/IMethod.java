package org.ctom.hulis.huckel.methods;

import java.util.ArrayList;

import org.ctom.hulis.huckel.Mesomery;
import org.ctom.hulis.huckel.exception.IMethodException;
import org.ctom.hulis.huckel.warning.IMethodWarning;


/**
 * This interface is implemented by classes that describe a method to calculate mesomery weights
 * @author ngoudard
 *
 */
public interface IMethod {
	
	/**
	 * This method calculate mesomery weights
	 * @throws IMethodException 
	 */
	public void calculate() throws IMethodException ;
	
	/**
	 * @return the priority of the method
	 */
	public int getPriority() ;
	
	/**
	 * @return a copy of the method
	 */
	public Object clone();

	/**
	 * @return the method Ci vector
	 */
	public double[] getCI();

	/**
	 * @return the method hamiltonian matrix
	 */
	public double[][] getHamiltonian();

	/**
	 * @return true if the method implements an hamiltonian, else return false
	 */
	public boolean isImplementedHamiltonian();

	/**
	 * 
	 * @return method name
	 */
	public String getName();

	/**
	 * 
	 * @return tau value
	 */
	public double getTau();

	/**
	 * 
	 * @return weights vector
	 */
	public double[] getWeights();

	/**
	 * 
	 * @return true if tau value calculation is implemented, else return false 
	 */
	public boolean isImplementedTau();

	/**
	 * This method sets the mesomery that implements this method
	 * @param mesomery that implements the method
	 */
	public void setMesomery(Mesomery mesomery);

	/**
	 * get the exceptions that causes a failure in the calculate method.
	 * @return Exception
	 */
	public IMethodException getError();
	
	/**
	 * get the warnings generated by the calculate method.
	 * @return ArrayList<IMethodWarning>
	 */
	public ArrayList<IMethodWarning> getWarnings();


}


