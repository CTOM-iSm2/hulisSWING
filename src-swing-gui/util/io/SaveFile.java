	private FrameApp app;

	public SaveFile(FrameApp app, File file)  throws Exception {
		DateFormat f = DateFormat.getDateTimeInstance(
		        DateFormat.FULL,
		        DateFormat.FULL, LanguageManager.getInstance().getLocale());	
		String messageHeader = "File generated by the " +FrameApp.ksoftname + " " + app.getVersion() + " code - " +  f.format(new Date()) ;
		this.app = app;
		MyResourceBundle bundle = LanguageManager.getInstance().getResource("ActionsApp");
		String type = file.getName().substring(
				file.getName().lastIndexOf('.') + 1).toLowerCase();
		System.out.println("type " + type);
		HuckelIO.log(this.getClass().getName(), "SaveFile", "file type = " + type);
		try {
			/*for (String t : ImageIO.getWriterFormatNames()) {
				System.out.println(t);
				if (type.equals(t)) {
					ImageIO.write(capture(), type, file);
					return;
				}
			}*/
			if (type.equals("png")){
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save png...");
				ImageIO.write(capture(), type, file);
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save png ok");
			}
			else if (type.equals("svg")){
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save svg");
				saveSVG(type, file);
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save svg ok");
			}
			else if (type.equals("xyz")) {
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save xyz");
				PrintWriterAdapter writer = new PrintWriterAdapter(file);
				IOWritexyz ioWritexyz = new IOWritexyz(app.getCurrentMesomery()
						.getDelocalizedStructure());
				ioWritexyz.setMessageHeader(messageHeader);
				ioWritexyz.setWriteInitialOrientation(JOptionPane.showConfirmDialog(app, bundle.getString("kinitialorientation") ,
						 "XYZ save file", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION);
				ioWritexyz.writeAll(writer);
				writer.close();
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save xyz ok");
			} else if (type.equals("com")) {
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save com");

				PrintWriterAdapter writer = new PrintWriterAdapter(file);
				IOWriteGaussian ioWriteGaussian = new IOWriteGaussian(app.getCurrentMesomery());
				ioWriteGaussian.setMessageHeader(messageHeader);
				ioWriteGaussian.setWriteInitialOrientation(JOptionPane.showConfirmDialog(app, bundle.getString("kinitialorientation"),
						 "NBO save file", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION);
				ioWriteGaussian.setNumberFormater(new SwingNumberFormater(new MyDecimalFormat(PreferencesGUI.getInstance().getResultsPrecisionMO())));
				ioWriteGaussian.writeAll(writer);
				writer.close();
				HuckelIO.log(this.getClass().getName(), "SaveFile", "Save com ok");
			} else if (type.equals("test")) {
				PrintWriterAdapter writer = new PrintWriterAdapter(file);
				new IOWriteGaussian(app.getCurrentMesomery()).writeAll(writer);
			}
			else if (type.equals("hulis")) {
			    	FileOutputStream fs = new FileOutputStream(file);
			         ObjectOutputStream os = new ObjectOutputStream(fs);
			         //TODO la serialization doit etre independante de clone()
			         // On ne doit pas serialiser les listeners faisaint partie de l'UI
			         os.writeObject(app.getCurrentMesomery().clone()); 
			         os.close();
			} else if (type.equals("xml")) {
				new SaveMesomeryToXML(app.getCurrentMesomery(), file).execute();
			}
			else
				throw new Exception("Format not found");
		} catch (IOException ioe) {
			HuckelIO.error(this.getClass().getName(), "SaveFile", "IOException");

			ioe.printStackTrace();
			MyJOptionPane.showMessageDialog(null, ioe.getMessage(), "Error",
					JOptionPane.ERROR_MESSAGE);
		}
		catch (Exception ioe) {
			HuckelIO.error(this.getClass().getName(), "SaveFile", "unknown exception");

			ioe.printStackTrace();
			MyJOptionPane.showMessageDialog(null, ioe.getMessage(), "Error",
					JOptionPane.ERROR_MESSAGE);
		}
	}
	
	
	public void saveSVG(String type, File file)
	{
		//do printing here
		try
		{
			DOMImplementation domImpl =
					GenericDOMImplementation.getDOMImplementation();
			Document document = domImpl.createDocument(null,
					"svg", null);
			SVGGraphics2D svgGenerator = new
					SVGGraphics2D(document);

			
			Structure s = this.app.getCurrentMesomeryView().getCurrentStructure();
			StructureView sw = this.app.getCurrentMesomeryView().getStructureView(s);
			
			sw.paint(svgGenerator);
			//
			svgGenerator.setSVGCanvasSize(sw.getPreferredSize());

			String useCssStr =
					System.getProperty("useCss", "true");
			boolean useCss =
					useCssStr.equalsIgnoreCase("true");

			FileOutputStream fos = new
					FileOutputStream(file);
			Writer outWriter = new OutputStreamWriter(fos,
					"UTF-8");
			svgGenerator.stream(outWriter, useCss);
			fos.flush();
			fos.close();
			outWriter.flush();
			outWriter.close();
			System.out.println(s.getName() + " has been saved in SVG");

		}

		catch (Exception exc)
		{

			exc.printStackTrace();
			MyJOptionPane.showMessageDialog(null, exc.getMessage(), "Error",
					JOptionPane.ERROR_MESSAGE);
		}
	}


	private BufferedImage capture() {
		// to save the whole panel Component c = app.mesomeryView();
		// to save the molecule only Component c =
		// app.mesomeryView.getStructureView(app.mesomeryView.getCurrentStructure());
		// to save molecule and spectrum Component c =
		// app.mesomeryView.getSelectedComponent();
		Structure s = this.app.getCurrentMesomeryView().getCurrentStructure();
		StructureView c = this.app.getCurrentMesomeryView().getStructureView(s);
		// BufferedImage tampon = new BufferedImage(c.getWidth(),c.getHeight(),
		// BufferedImage.TYPE_INT_RGB);
		BufferedImage tampon = new BufferedImage(c.getWidth(), c.getHeight(),
				BufferedImage.TYPE_INT_RGB);
		Graphics g = tampon.createGraphics();
		c.paint(g);
		return tampon;
	}

	private int[] getWindow() {
		int Extrema[] = new int[4];
		Extrema[0] = -1;
		Extrema[1] = -1;
		Extrema[2] = 9999;
		Extrema[3] = 9999;
		for (Atom atom : this.app.getCurrentMesomeryView().getCurrentStructure().getAtoms()) {
			Extrema[0] = Math.max((int) atom.getX(), Extrema[0]);
			Extrema[1] = Math.max((int) atom.getY(), Extrema[1]);
			Extrema[2] = Math.min((int) atom.getX(), Extrema[2]);
			Extrema[3] = Math.min((int) atom.getY(), Extrema[3]);
		}
		return Extrema;
	}
