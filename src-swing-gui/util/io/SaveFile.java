	public SaveFile(FrameApp app, File file)  throws Exception {
		DateFormat f = DateFormat.getDateTimeInstance(
		        DateFormat.FULL,
		        DateFormat.FULL, LanguageManager.getInstance().getLocale());	
		messageHeader = "File generated by the " +FrameApp.ksoftname + " " + app.getVersion() + " code - " +  f.format(new Date()) ;
		this.app = app;
		bundle = LanguageManager.getInstance().getResource("ActionsApp");
		String type = file.getName().substring(
				file.getName().lastIndexOf('.') + 1).toLowerCase();
		System.out.println("type " + type);
		HuckelIO.log(this.getClass().getName(), "SaveFile", "file type = " + type);
	
		/*for (String t : ImageIO.getWriterFormatNames()) {
			System.out.println(t);
			if (type.equals(t)) {
				ImageIO.write(capture(), type, file);
				return;
			}
		}*/
		if (type.equals("png")){
			HuckelIO.log(this.getClass().getName(), "SaveFile", "Save png...");
			ImageIO.write(capture(), type, file);
			HuckelIO.log(this.getClass().getName(), "SaveFile", "Save png ok");
		}
		else if (type.equals("svg")){
			saveSVG(type, file);
		}
		else if (type.equals("xyz")) {
			saveXYZ(type, file);
		} else if (type.equals("com")) {
			saveGaussian(type, file);
		} else if (type.equals("tcom")) {
			PrintWriter writer = new PrintWriter(file);
			new WriteGaussianTest(app.getCurrentMesomery()).writeAll(writer);
			writer.close();
		}
		else if (type.equals("hulis")) {
			saveSeralizedFormat(type, file);
		} else if (type.equals("txml")) {
			new SaveMesomeryToXML(app.getCurrentMesomery(), file).execute();
		}
		else
			MyJOptionPane.showMessageDialog(null, "Format nnot found", "Error",
					JOptionPane.ERROR_MESSAGE);
	
		
	}
	
	
	/**
	 * 
	 * @param type
	 * @param file
	 */
	public void saveSeralizedFormat(String type, File file) {
		try {
			FileOutputStream fs = new FileOutputStream(file);
			 ObjectOutputStream os = new ObjectOutputStream(fs);
	        //TODO la serialization doit etre independante de clone()
	        // On ne doit pas serialiser les listeners faisaint partie de l'UI
	        os.writeObject(app.getCurrentMesomery().clone()); 
	        os.close();
		} catch (IOException e) {
			e.printStackTrace();
			MyJOptionPane.showMessageDialog(null, e.getMessage(), "Error",
					JOptionPane.ERROR_MESSAGE);

		}
       
	}
	
	/**
	 * 
	 * @param type
	 * @param file
	 */
	public void saveXYZ(String type, File file) {
		HuckelIO.log(this.getClass().getName(), "SaveFile", "Save file .xyz");
		
		try {
			PrintWriter writer = new PrintWriter(file);
			Writexyz ioWritexyz = new Writexyz(app.getCurrentMesomery()
					.getDelocalizedStructure());
			ioWritexyz.setMessageHeader(messageHeader);
			if (this.app.getCurrentMesomery().getDelocalizedStructure().isGeometryChanged() ) {
				ioWritexyz.setWriteInitialOrientation(false);
				JOptionPane.showMessageDialog(app, "Cannot restore the initial orientation, the molecule has changed. The molecule will be saved with the new orientation." , "save XYZ", JOptionPane.INFORMATION_MESSAGE);
			
			}
			else {
				ioWritexyz.setWriteInitialOrientation(JOptionPane.showConfirmDialog(app, bundle.getString("kinitialorientation") ,
						 "XYZ save file", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION);
			}		
			List<HuckelBond> covRadii= this.app.getCurrentMesomery().getDelocalizedStructure().checkBondsCovalentRaii();
			if (covRadii.size()>0)
				JOptionPane.showMessageDialog(app, "The geometry is not optimized. Some bonds may have been missed after reading the file in HuLiS : " + covRadii.stream().map(Object::toString).collect(Collectors.joining(", ")),  "save XYZ", JOptionPane.INFORMATION_MESSAGE);
			ioWritexyz.writeAll(writer);
			writer.close();
			HuckelIO.log(this.getClass().getName(), "Save " + type, "Save " + type + " ok");
		} catch (FileNotFoundException | WritexyzException e) {
			e.printStackTrace();
			MyJOptionPane.showMessageDialog(null, e.getMessage(), "Save" + type,
					JOptionPane.ERROR_MESSAGE);
		}
		
	}
	
	/**
	 * 
	 * @param type
	 * @param file
	 */
	public void saveGaussian(String type, File file) {
		HuckelIO.log(this.getClass().getName(), "Save Gaussian", "Save file .com");

		try {
			PrintWriter writer = new PrintWriter(file);
			WriteGaussian ioWriteGaussian = new WriteGaussian(app.getCurrentMesomery());
			ioWriteGaussian.setMessageHeader(messageHeader);
			if (this.app.getCurrentMesomery().getDelocalizedStructure().isGeometryChanged() ) {
				ioWriteGaussian.setWriteInitialOrientation(false);
				JOptionPane.showMessageDialog(app, "Cannot restore the initial orientation, the molecule has changed. The molecule will be saved with the new orientation." , messageHeader, JOptionPane.INFORMATION_MESSAGE);			
			}
			else {
				ioWriteGaussian.setWriteInitialOrientation(JOptionPane.showConfirmDialog(app, bundle.getString("kinitialorientation"),
						 "NBO save file", JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION);
			}
			List<HuckelBond> covRadii= this.app.getCurrentMesomery().getDelocalizedStructure().checkBondsCovalentRaii();
			if (covRadii.size()>0)
				JOptionPane.showMessageDialog(app, "The geometry is not optimized. Some bonds may have been missed after reading the file in HuLiS : " + covRadii.stream().map(Object::toString).collect(Collectors.joining(", ")), messageHeader, JOptionPane.INFORMATION_MESSAGE);
			ioWriteGaussian.setNumberFormater(new SwingNumberFormater(new MyDecimalFormat(PreferencesGUI.getInstance().getResultsPrecisionMO())));
			ioWriteGaussian.writeAll(writer);
			writer.close();
			HuckelIO.log(this.getClass().getName(), "Save " + type, "Save " + type + " ok");
		} catch (FileNotFoundException | WritexyzException e) {
			e.printStackTrace();
			MyJOptionPane.showMessageDialog(null, e.getMessage(), "Save" + type,
					JOptionPane.ERROR_MESSAGE);
		}
		
		
	}
	
	
	/**
	 * 
	 * @param type
	 * @param file
	 */
	public void saveSVG(String type, File file)
	{
		//do printing here
		try
		{
			HuckelIO.log(this.getClass().getName(), "SaveFile", "Save" + type);
					DOMImplementation domImpl =
					GenericDOMImplementation.getDOMImplementation();
			Document document = domImpl.createDocument(null,
					"svg", null);
			SVGGraphics2D svgGenerator = new
					SVGGraphics2D(document);

			
			Structure s = this.app.getCurrentMesomeryView().getCurrentStructure();
			StructureView sw = this.app.getCurrentMesomeryView().getStructureView(s);
			
			sw.paint(svgGenerator);
			//
			svgGenerator.setSVGCanvasSize(sw.getPreferredSize());

			String useCssStr =
					System.getProperty("useCss", "true");
			boolean useCss =
					useCssStr.equalsIgnoreCase("true");

			FileOutputStream fos = new
					FileOutputStream(file);
			Writer outWriter = new OutputStreamWriter(fos,
					"UTF-8");
			svgGenerator.stream(outWriter, useCss);
			fos.flush();
			fos.close();
			outWriter.flush();
			outWriter.close();
			System.out.println(s.getName() + " has been saved in SVG");
			HuckelIO.log(this.getClass().getName(), "SaveFile", "Save" + type + "ok");
			
		}

		catch (Exception exc)
		{

			exc.printStackTrace();
			MyJOptionPane.showMessageDialog(null, exc.getMessage(), "Error",
					JOptionPane.ERROR_MESSAGE);
		}
	}


